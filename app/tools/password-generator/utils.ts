// Have I Been Pwned (HIBP) k-anonymity check
export async function checkPasswordPwned(password: string): Promise<{
  isPwned: boolean
  count: number
  error?: string
}> {
  try {
    // Hash the password with SHA-1
    const encoder = new TextEncoder()
    const data = encoder.encode(password)
    const hashBuffer = await crypto.subtle.digest('SHA-1', data)
    const hashArray = Array.from(new Uint8Array(hashBuffer))
    const hashHex = hashArray
      .map((b) => b.toString(16).padStart(2, '0'))
      .join('')
      .toUpperCase()

    // Use k-anonymity: send only first 5 chars of hash
    const prefix = hashHex.slice(0, 5)
    const suffix = hashHex.slice(5)

    const response = await fetch(`https://api.pwnedpasswords.com/range/${prefix}`)

    if (!response.ok) {
      return { isPwned: false, count: 0, error: 'Failed to check password' }
    }

    const text = await response.text()
    const lines = text.split('\n')

    // Check if our suffix is in the results
    for (const line of lines) {
      const [hashSuffix, countStr] = line.split(':')
      if (hashSuffix === suffix) {
        return { isPwned: true, count: parseInt(countStr.trim(), 10) }
      }
    }

    return { isPwned: false, count: 0 }
  } catch (error) {
    return {
      isPwned: false,
      count: 0,
      error: error instanceof Error ? error.message : 'Unknown error',
    }
  }
}

