// Password generation and strength calculation utilities
import type { ZXCVBNResult } from 'zxcvbn'
import zxcvbnImport from 'zxcvbn'

const zxcvbn = zxcvbnImport as (password: string, userInputs?: string[]) => ZXCVBNResult

interface PasswordOptions {
  length: number
  uppercase: boolean
  lowercase: boolean
  numbers: boolean
  symbols: boolean
}

interface StrengthResult {
  score: number // 0-4 from zxcvbn
  label: string // Weak, Fair, Good, Strong, Very Strong
  color: string // Tailwind color
  feedback: string[] // Suggestions from zxcvbn
  entropy?: number // Bits of entropy
  crackTime?: string // Human-readable crack time
  crackTimeSeconds?: number // Crack time in seconds
}

export interface PasswordPattern {
  type: 'random' | 'diceware' | 'pronounceable' | 'template'
  name: string
  description: string
  template?: string
}

export interface PasswordHistory {
  password: string
  timestamp: number
  strength: StrengthResult
  favorite: boolean
  length: number
}

export interface PasswordTemplate {
  id: string
  name: string
  description: string
  pattern: string
  example: string
  category: 'banking' | 'social' | 'wifi' | 'email' | 'custom'
}

