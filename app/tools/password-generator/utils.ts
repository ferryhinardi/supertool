// Pronounceable consonant-vowel patterns
const VOWELS = 'aeiou'
const CONSONANTS = 'bcdfghjklmnpqrstvwxyz'

// Cryptographically secure password generation
export function generatePassword(options: PasswordOptions): string {
  let charset = ''
  if (options.uppercase) charset += CHAR_SETS.uppercase
  if (options.lowercase) charset += CHAR_SETS.lowercase
  if (options.numbers) charset += CHAR_SETS.numbers
  if (options.symbols) charset += CHAR_SETS.symbols

  if (charset === '') {
    throw new Error('At least one character set must be selected')
  }

  const password: string[] = []
  const randomValues = new Uint32Array(options.length)
  crypto.getRandomValues(randomValues)

  for (let i = 0; i < options.length; i++) {
    const randomIndex = randomValues[i] % charset.length
    password.push(charset[randomIndex])
  }

  return password.join('')
}

// Generate a diceware passphrase
export function generateDiceware(wordCount = 6, separator = '-'): string {
  const words: string[] = []
  const randomValues = new Uint32Array(wordCount)
  crypto.getRandomValues(randomValues)

  for (let i = 0; i < wordCount; i++) {
    const randomIndex = randomValues[i] % DICEWARE_WORDS.length
    words.push(DICEWARE_WORDS[randomIndex])
  }

  return words.join(separator)
}

// Generate a pronounceable password
export function generatePronounceable(length: number): string {
  const password: string[] = []
  const randomValues = new Uint32Array(length)
  crypto.getRandomValues(randomValues)

  for (let i = 0; i < length; i++) {
    // Alternate between consonants and vowels for pronounceability
    const useVowel = i % 2 === 1
    const charset = useVowel ? VOWELS : CONSONANTS
    const randomIndex = randomValues[i] % charset.length
    password.push(charset[randomIndex])
  }

  return password.join('')
}

