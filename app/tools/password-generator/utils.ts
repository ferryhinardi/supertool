// Generate password from template
export function generateFromTemplate(templateId: string): string {
  const template = PASSWORD_TEMPLATES.find((t) => t.id === templateId)
  if (!template) {
    throw new Error('Template not found')
  }

  const { pattern } = template
  const password: string[] = []
  const randomValues = new Uint32Array(pattern.length)
  crypto.getRandomValues(randomValues)

  let randomIndex = 0
  for (const char of pattern) {
    if (char === 'A') {
      // Uppercase letter
      const index = randomValues[randomIndex++] % CHAR_SETS.uppercase.length
      password.push(CHAR_SETS.uppercase[index])
    } else if (char === 'a') {
      // Lowercase letter
      const index = randomValues[randomIndex++] % CHAR_SETS.lowercase.length
      password.push(CHAR_SETS.lowercase[index])
    } else if (char === '1') {
      // Number
      const index = randomValues[randomIndex++] % CHAR_SETS.numbers.length
      password.push(CHAR_SETS.numbers[index])
    } else if (char === '!') {
      // Symbol
      const index = randomValues[randomIndex++] % CHAR_SETS.symbols.length
      password.push(CHAR_SETS.symbols[index])
    } else {
      // Keep literal character (like '-')
      password.push(char)
    }
  }

  return password.join('')
}

// Calculate password strength using zxcvbn
export function calculateStrength(password: string): StrengthResult {
  if (!password) {
    return {
      score: 0,
      label: 'No Password',
      color: 'gray.500',
      feedback: ['Enter a password to see strength analysis'],
      entropy: 0,
      crackTime: 'Instant',
      crackTimeSeconds: 0,
    }
  }

  const result = zxcvbn(password)
  const feedback: string[] = []

  // Extract feedback from zxcvbn
  if (result.feedback.warning) {
    feedback.push(result.feedback.warning)
  }
  if (result.feedback.suggestions && result.feedback.suggestions.length > 0) {
    feedback.push(...result.feedback.suggestions)
  }

  // Calculate entropy (bits)
  const entropy = Math.log2(getCharsetSize(password) ** password.length)

  // Format crack time display (offline_slow_hashing_1e4_per_second is always a number)
  const crackTimeSecondsValue =
    typeof result.crack_times_seconds.offline_slow_hashing_1e4_per_second === 'number'
      ? result.crack_times_seconds.offline_slow_hashing_1e4_per_second
      : 0
  const crackTime = formatCrackTime(crackTimeSecondsValue)
  const crackTimeSeconds = crackTimeSecondsValue

  // Map zxcvbn score (0-4) to our labels and colors
  const scoreMap = [
    { label: 'Very Weak', color: '#ef4444' }, // red-500
    { label: 'Weak', color: '#f97316' }, // orange-500
    { label: 'Fair', color: '#eab308' }, // yellow-500
    { label: 'Strong', color: '#22c55e' }, // green-500
    { label: 'Very Strong', color: '#10b981' }, // emerald-500
  ]

  const { label, color } = scoreMap[result.score]

  return {
    score: result.score,
    label,
    color,
    feedback: feedback.length > 0 ? feedback : ['Password strength analyzed'],
    entropy: Math.round(entropy * 10) / 10,
    crackTime,
    crackTimeSeconds,
  }
}

// Get charset size based on characters used
function getCharsetSize(password: string): number {
  let size = 0
  if (/[a-z]/.test(password)) size += 26 // lowercase
  if (/[A-Z]/.test(password)) size += 26 // uppercase
  if (/[0-9]/.test(password)) size += 10 // numbers
  if (/[^a-zA-Z0-9]/.test(password)) size += 33 // symbols
  return size || 1
}

// Format crack time in human-readable format
function formatCrackTime(seconds: number): string {
  if (seconds < 1) return 'Instant'
  if (seconds < 60) return `${Math.round(seconds)} seconds`
  if (seconds < 3600) return `${Math.round(seconds / 60)} minutes`
  if (seconds < 86400) return `${Math.round(seconds / 3600)} hours`
  if (seconds < 2592000) return `${Math.round(seconds / 86400)} days`
  if (seconds < 31536000) return `${Math.round(seconds / 2592000)} months`
  if (seconds < 3153600000) return `${Math.round(seconds / 31536000)} years`
  return 'Centuries'
}

// Password History Management
const HISTORY_KEY = 'password-generator-history'
const MAX_HISTORY = 10

export function savePasswordToHistory(password: string): void {
  try {
    const history = getPasswordHistory()
    const strength = calculateStrength(password)

    const entry: PasswordHistory = {
      password,
      timestamp: Date.now(),
      strength,
      favorite: false,
      length: password.length,
    }

    // Add to beginning, remove duplicates
    const filtered = history.filter((h) => h.password !== password)
    const updated = [entry, ...filtered].slice(0, MAX_HISTORY)

    localStorage.setItem(HISTORY_KEY, JSON.stringify(updated))
  } catch (error) {
    console.error('Failed to save password to history:', error)
  }
}

export function getPasswordHistory(): PasswordHistory[] {
  try {
    const stored = localStorage.getItem(HISTORY_KEY)
    if (!stored) return []
    const parsed: unknown = JSON.parse(stored)
    if (!Array.isArray(parsed)) return []
    return parsed as PasswordHistory[]
  } catch {
    return []
  }
}

