describe('Gradient Generator - Color Stop Management', () => {
  beforeEach(() => {
    queryClient = new QueryClient({
      defaultOptions: {
        queries: { retry: false },
      },
    })
    vi.clearAllMocks()
  })

  it('should update color stop color', () => {
    renderPage()

    const colorInputs = screen.getAllByRole('textbox')
    const firstInput = colorInputs[0]

    fireEvent.change(firstInput, { target: { value: '#ff0000' } })

    expect(firstInput).toHaveValue('#ff0000')
  })

  it('should update color stop position', () => {
    renderPage()

    // Find position sliders (range inputs)
    const sliders = document.querySelectorAll('input[type="range"]')
    const colorStopSlider = Array.from(sliders).find(
      (slider) =>
        slider.getAttribute('min') === '0' &&
        slider.getAttribute('max') === '100' &&
        !slider.closest('[data-angle-control]')
    )

    if (colorStopSlider) {
      fireEvent.change(colorStopSlider, { target: { value: '75' } })
      expect(colorStopSlider).toHaveValue('75')
    }
  })
})

