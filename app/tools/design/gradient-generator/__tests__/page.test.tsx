describe('Gradient Generator Page - Component Tests', () => {
  beforeEach(() => {
    queryClient = new QueryClient({
      defaultOptions: {
        queries: { retry: false },
      },
    })
    vi.clearAllMocks()
  })

  it('should render gradient generator page', () => {
    renderPage()

    expect(
      screen.getByRole('heading', { name: 'Gradient Generator', level: 1 })
    ).toBeInTheDocument()
    expect(screen.getByRole('heading', { name: 'Preview', level: 2 })).toBeInTheDocument()
    expect(screen.getByRole('heading', { name: 'Gradient Controls', level: 2 })).toBeInTheDocument()
    expect(screen.getByRole('heading', { name: 'Gradient Presets', level: 2 })).toBeInTheDocument()
  })

  it('should display gradient type buttons', () => {
    renderPage()

    expect(screen.getByRole('button', { name: 'linear' })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'radial' })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'conic' })).toBeInTheDocument()
  })

  it('should have linear gradient selected by default', () => {
    renderPage()

    const _linearButton = screen.getByRole('button', { name: 'linear' })
    // Check that linear gradient CSS is generated by default
    // Use getAllByText to handle multiple matches, then filter for the <pre> element
    const cssOutputs = screen.getAllByText(/background:/)
    const cssOutput = cssOutputs.find((el) => el.tagName === 'PRE')
    expect(cssOutput).toBeDefined()
    expect(cssOutput?.textContent).toContain('linear-gradient')
  })

  it('should display default color stops', () => {
    renderPage()

    // Should have 2 default color stops
    const colorInputs = screen.getAllByRole('textbox')
    expect(colorInputs.length).toBeGreaterThanOrEqual(2)
  })

  it('should display angle control for linear gradient', () => {
    renderPage()

    expect(screen.getByText(/Angle:/)).toBeInTheDocument()
  })

  it('should display action buttons', () => {
    renderPage()

    expect(screen.getByRole('button', { name: /Copy CSS/ })).toBeInTheDocument()
    expect(screen.getByRole('button', { name: /Download PNG/ })).toBeInTheDocument()
  })

  it('should switch gradient types', async () => {
    renderPage()

    const radialButton = screen.getByRole('button', { name: 'radial' })
    await userEvent.click(radialButton)

    // Angle control should not be visible for radial gradients
    expect(screen.queryByText(/Angle:/)).not.toBeInTheDocument()
  })

  it('should add a new color stop', async () => {
    renderPage()

    const addButton = screen.getByRole('button', { name: /Add/ })
    const initialColorInputs = screen.getAllByRole('textbox').length

    await userEvent.click(addButton)

    const newColorInputs = screen.getAllByRole('textbox').length
    expect(newColorInputs).toBe(initialColorInputs + 1)
  })

  it('should copy CSS to clipboard', async () => {
    renderPage()

    const copyButton = screen.getByRole('button', { name: /Copy CSS/ })
    await userEvent.click(copyButton)

    await waitFor(() => {
      expect(navigator.clipboard.writeText).toHaveBeenCalled()
    })
  })

  it('should randomize gradient', async () => {
    renderPage()

    const randomizeButton = screen.getAllByRole('button').find((btn) => {
      const svg = btn.querySelector('svg')
      return svg?.getAttribute('class')?.includes('lucide-shuffle')
    })

    expect(randomizeButton).toBeInTheDocument()
    if (randomizeButton) {
      await userEvent.click(randomizeButton)
      // Gradient should be randomized (visual change, hard to test)
    }
  })

  it('should reverse gradient', () => {
    renderPage()

    const reverseButton = screen.getAllByRole('button').find((btn) => {
      const svg = btn.querySelector('svg')
      return svg?.getAttribute('class')?.includes('lucide-rotate-ccw')
    })

    expect(reverseButton).toBeInTheDocument()
  })

  it('should toggle preview background', async () => {
    renderPage()

    // Find the preview background toggle button
    const toggleButtons = screen.getAllByRole('button')
    const previewToggle = toggleButtons.find((btn) => {
      return btn.querySelector('svg.lucide-sun') || btn.querySelector('svg.lucide-moon')
    })

    expect(previewToggle).toBeInTheDocument()
    if (previewToggle) {
      await userEvent.click(previewToggle)
      // Background should toggle (visual change)
    }
  })

  it('should prevent removing color stops when only 2 remain', () => {
    renderPage()

    // Try to find and click remove button on a color stop
    const deleteButtons = screen.getAllByRole('button').filter((btn) => {
      const svg = btn.querySelector('svg')
      return svg?.getAttribute('class')?.includes('lucide-trash-2')
    })

    // If there are only 2 color stops, no delete buttons should be visible
    expect(deleteButtons.length).toBe(0)
  })
})

